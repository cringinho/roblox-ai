def supported(ch: str) -> bool:
    return ch.translate(ACCENTS).upper() in _G


def glyph(ch: str) -> np.ndarray:
    key = ch.translate(ACCENTS).upper()
    rows = _G.get(key)
    if rows is None:
        raise KeyError(f"glifo nao suportado: {ch!r} (U+{ord(ch):04X})")
    return np.array([[c == "#" for c in r] for r in rows], dtype=bool)


def text_mask(text: str, scale: int = 1, spacing: int = 1, bold: bool = False) -> np.ndarray:
    """Mascara booleana do texto. bold engrossa hastes verticais (look de gravura/blackletter)."""
    gl = [glyph(ch) for ch in text]
    w = sum(g.shape[1] for g in gl) + spacing * (len(gl) - 1)
    h = 7
    m = np.zeros((h, max(1, w)), dtype=bool)
    x = 0
    for g in gl:
        m[:, x:x + g.shape[1]] |= g
        x += g.shape[1] + spacing
    if bold:
        b = m.copy()
        b[:, 1:] |= m[:, :-1]
        m = b
    if scale > 1:
        m = np.repeat(np.repeat(m, scale, axis=0), scale, axis=1)
    return m
